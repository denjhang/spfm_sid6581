"""Generate src/sid_freq_table.c from the SID pitch formula.

    freq_reg = round(f_out * 16777216 / PHI2)

Cross-checks the result against the freq[] table in arduino_sid/midi.c and
prints every entry that differs (the reference table has two documented bugs:
note 23 is a copy-paste of C#1, and everything from note 99 up is shifted by
one semitone).
"""
import re

SRC = r"E:/working/zcode-projects/arduino_sid/midi.c"
OUT = r"E:/working/zcode-projects/spfm_sid6581/src/sid_freq_table.c"
PHI2 = 1_000_000.0
NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]


def name(n):
    return NAMES[n % 12] + str(n // 12 - 1)


def freq_reg(note):
    hz = 440.0 * pow(2.0, (note - 69) / 12.0)
    return int(round(hz * 16777216.0 / PHI2))


def main():
    table = [min(freq_reg(n), 0xFFFF) for n in range(128)]

    lines = []
    lines.append("/* Generated by tools/gen_freq.py - do not edit by hand.")
    lines.append(" * PHI2 = 1.000 MHz, freq_reg = round(440 * 2^((n-69)/12) * 2^24 / PHI2)")
    lines.append(" * index 0 = MIDI note 0 (C-1), index 127 = G9 */")
    lines.append("")
    lines.append('#include "sid6581.h"')
    lines.append("")
    lines.append("const uint16_t sid_freq_table[128] = {")
    for base in range(0, 128, 8):
        chunk = table[base:base + 8]
        cells = ", ".join("%5d" % v for v in chunk)
        lines.append("    %s,  /* %3d %-4s */" % (cells, base, name(base)))
    lines.append("};")
    lines.append("")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote", OUT)

    # cross-check against the reference table
    src = open(SRC, encoding="utf-8", errors="replace").read()
    m = re.search(r"int\s+freq\s*\[\s*\]\s*=\s*\{(.*?)\}\s*;", src, re.S)
    ref = [int(x) for x in re.findall(r"\d+", m.group(1).replace("\\", ""))]
    print("reference table entries:", len(ref))
    diffs = 0
    for n, v in enumerate(ref):
        if n >= 12 and v and v != table[n]:
            diffs += 1
            print("  note %3d %-4s ref=%5d correct=%5d" % (n, name(n), v, table[n]))
    print("entries differing from formula:", diffs)


if __name__ == "__main__":
    main()
